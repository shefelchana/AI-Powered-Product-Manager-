// Импорт текста урока. Человек вставляет текст как есть — с переводами,
// номерами страниц, пометками, — а сюда попадает работа, которую скучно
// делать руками: выловить ивритские слова, убрать огласовки и повторы.
// Что из кандидатов станет карточками — решает человек галочками: функция
// не должна терять слова и не должна подсовывать мусор, угадывать — не её дело.

// Убираем знаки кантилляции и огласовки (U+0591–U+05C7): в колоде слова
// живут в обычном письме, как их печатают в сообщениях и субтитрах.
const stripNiqqud = (text) => text.replace(/[֑-ׇ]/g, "");

// Слово — подряд идущие ивритские буквы; внутри допускаются гереш и гершаим
// (צה"ל, ג׳ינס) и дефис-макаф. Крайние кавычки-обёртки словами не считаются.
const WORD = /[א-ת][א-ת"'׳״־-]*[א-ת"״]|[א-ת]{2,}/g;

export function extractTerms(text) {
  const clean = stripNiqqud(String(text ?? ""));
  const seen = new Set();
  const terms = [];
  for (const match of clean.match(WORD) ?? []) {
    // Одиночная буква — почти всегда союз или предлог, оторвавшийся от слова.
    const letters = match.replace(/[^א-ת]/g, "");
    if (letters.length < 2) continue;
    if (!seen.has(match)) {
      seen.add(match);
      terms.push(match);
    }
  }
  return terms;
}
